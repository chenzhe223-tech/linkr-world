/** 某城的住宿清单 */
export function staysOfCity(cityId: CityId): Stay[] {
  return STAYS.filter((s) => s.cityId === cityId);
}

const TIER_ORDER: StayTier[] = ['国际连锁', '国内连锁', '度假奢华', '精品民宿'];

/** 稳定排序：先按层级，再按钻级降序，最后按名称 */
export function sortStays(list: Stay[]): Stay[] {
  return [...list].sort((a, b) => {
    const t = TIER_ORDER.indexOf(a.tier) - TIER_ORDER.indexOf(b.tier);
    if (t !== 0) return t;
    if (b.diamond !== a.diamond) return b.diamond - a.diamond;
    return a.name.localeCompare(b.name, 'zh-Hans-CN');
  });
}

export interface StayMatch {
  stay: Stay;
  /** 命中的个性化标签 */
  hits: StayTag[];
  /** 推荐理由（一句话） */
  reason: string;
}

/**
 * 个性化匹配：按同行人、行程关键词与预算档给住宿打分并排序。
 * 只做「排序 + 说明理由」，不臆造任何酒店事实。
 */
export function matchStays(
  cityId: CityId,
  opts: { companions?: string; keywords?: string[]; budgetFriendly?: boolean } = {}
): StayMatch[] {
  const comp = opts.companions ?? '';
  const kws = (opts.keywords ?? []).join(' ');
  const hay = `${comp} ${kws}`;

  const wanted: StayTag[] = [];
  if (/独行|一个人|独自/.test(hay)) wanted.push('独行');
  if (/情侣|朋友|双人|二人/.test(hay)) wanted.push('情侣');
  if (/亲子|孩子|带娃|娃/.test(hay)) wanted.push('亲子');
  if (/父母|爸妈|老人|长辈/.test(hay)) wanted.push('带父母');
  if (/拍照|出片|摄影|写真/.test(hay)) wanted.push('摄影');
  if (/温泉|泡汤|热海/.test(hay)) wanted.push('温泉');
  if (/洱海|海景|看海|湖/.test(hay)) wanted.push('海景');
  if (/古城|古镇|打卡|逛街/.test(hay)) wanted.push('古城步行');
  if (/不赶|慢|度假|躺|放松/.test(hay)) wanted.push('度假');
  if (/秘境|小众|避开人群|清静|安静/.test(hay)) wanted.push('秘境');
  if (opts.budgetFriendly || /省|预算|性价比|穷游/.test(hay)) wanted.push('性价比');

  const scored = staysOfCity(cityId).map((stay) => {
    const hits = stay.bestFor.filter((t) => wanted.includes(t));
    // 钻级作为弱权重，避免把"贵"当成唯一标准
    const score = hits.length * 10 + stay.diamond;
    return { stay, hits, score };
  });

  scored.sort((a, b) => b.score - a.score || b.stay.diamond - a.stay.diamond);

  return scored.map(({ stay, hits }) => ({
    stay,
    hits,
    reason: buildReason(stay, hits),
  }));
}

function buildReason(stay: Stay, hits: StayTag[]): string {
  const tagPhrase: Record<StayTag, string> = {
    独行: '一个人住也自在',
    情侣: '适合两个人的空间',
    亲子: '带孩子住得开',
    带父母: '带长辈不折腾',
    摄影: '取景条件好',
    温泉: '泡汤是它的正题',
    海景: '看得见水',
    古城步行: '出门就在古城里',
    性价比: '把钱省给行程',
    度假: '适合整天待在酒店',
    秘境: '安静得离开人群',
  };
  const head = `${stay.brand}·${stay.area}`;
  if (hits.length === 0) return `${head} · ${stay.diamond} 钻，条件均衡的一个选项。`;
  return `${head} · ${hits.map((h) => tagPhrase[h]).join('、')}。`;
}

/** 携程核验链接（页面可点开自行核对） */
export function ctripUrl(stay: Stay): string {
  return `https://hotels.ctrip.com/hotels/detail/?hotelId=${stay.ctripId}`;
}

/** 全部品牌集团（用于筛选器） */
export function allBrandGroups(): string[] {
  return Array.from(new Set(STAYS.map((s) => s.brandGroup))).sort((a, b) =>
    a.localeCompare(b, 'zh-Hans-CN')
  );
}

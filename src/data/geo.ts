/** 地名归一：去"市/地区"后缀与空白 */
export function normalizeCityName(input: string): string {
  return input.trim().replace(/[市地区县]+$/u, '');
}

/** 识别出发地；未收录返回 null */
export function findOrigin(input: string): OriginCity | null {
  const key = normalizeCityName(input);
  if (!key) return null;
  return (
    ORIGINS.find((c) => c.name === key) ??
    ORIGINS.find((c) => c.name.startsWith(key) || key.startsWith(c.name)) ??
    null
  );
}
